WALKRA = 0x1A0                                   # scratch word: the return address of the walk subroutine

def walk(a, tagname, layer=LAYER, open_end=False, end_layer=None):
    """one walk of layer LAYER (up to the head of END_LAYER): a call of the shared subroutine WALKSUB (2026-11-13: the walk code used to be copied at every call site, 110 words each)"""
    a.emit('addiu', 'a2', 'a0', 16 * layer)
    a.emit('addiu', 'a3', 'a0', 16 * (end_layer or layer + 1))
    a.emit('ori', 'k0', 'zero', 1 if open_end else 0)
    a.emit('jal', 'WALKSUB'); a.emit('nop')

def walk_body(a):
    """the shared walk: a2 = head of the layer, a3 = where the walk stops, k0 = 1 for the open walk of layer 0xA3 (see below); a0 / a1 = chain base / limit; returns with jr ra"""
